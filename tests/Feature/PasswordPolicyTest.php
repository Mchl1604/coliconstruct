    }

    public function test_the_account_service_refuses_a_weak_password_from_any_caller(): void
    {
        $accounts = app(UserAccountService::class);

        $attempts = [
            fn () => $accounts->createEmployee([
                'first_name' => 'Ana', 'last_name' => 'Mendoza', 'contact_number' => '09175551234',
                'birthdate' => '1990-05-04', 'email' => 'ana@example.test', 'role' => 'admin',
                'password' => 'password1',
            ]),
            fn () => $accounts->createClient([
                'full_name' => 'Jose Garcia', 'contact_number' => '09175551234',
                'birthdate' => '1988-11-20', 'email' => 'jose@example.test', 'password' => 'Password!',
            ]),
            fn () => $accounts->startRegistration([
                'full_name' => 'Maria Santos', 'contact_number' => '09175551234',
                'birthdate' => '1988-11-20', 'email' => 'maria@example.test', 'password' => 'PASSWORD1!',
            ]),
            fn () => $accounts->registerClient([
                'full_name' => 'Maria Santos', 'contact_number' => '09175551234',
                'birthdate' => '1988-11-20', 'email' => 'maria@example.test', 'password' => 'password!',
            ]),
        ];

        foreach ($attempts as $attempt) {
            try {
                $attempt();
                $this->fail('A weak password was accepted.');
            } catch (RuntimeException $exception) {
                $this->assertStringStartsWith('Password must', $exception->getMessage());
            }
        }

        $this->assertSame(0, User::count());
        $this->assertDatabaseCount('tbl_pending_registrations', 0);
    }

    public function test_the_repair_command_refuses_a_weak_shared_password_and_changes_nothing(): void
    {
        $broken = $this->account('technician');
        DB::table('users')->where('id', $broken->id)->update(['password' => 'placeholder']);

        $this->artisan('users:repair-passwords', ['--password' => 'password1'])
            ->expectsOutputToContain('Password must contain at least one uppercase letter and one special character.')
            ->assertExitCode(RepairUnusablePasswords::FAILURE);

        $this->assertSame('placeholder', DB::table('users')->where('id', $broken->id)->value('password'));
    }

    public function test_the_super_admin_seeder_refuses_a_weak_password(): void
    {
        $this->withSuperAdminPassword('1234567', function (): void {
            try {
                app(SuperAdminSeeder::class)->run();
                $this->fail('The seeder accepted a weak password.');
            } catch (RuntimeException $exception) {
                $this->assertStringContainsString('SUPER_ADMIN_PASSWORD does not meet the password policy.', $exception->getMessage());
                // The value itself is never repeated back.
                $this->assertStringNotContainsString('1234567', $exception->getMessage());
            }
        });

        $this->assertSame(0, User::count());

        $this->withSuperAdminPassword(self::STRONG, function (): void {
            app(SuperAdminSeeder::class)->run();
        });

        $owner = User::where('role', User::ROLE_SUPER_ADMIN)->firstOrFail();
        $this->assertTrue(Hash::check(self::STRONG, $owner->password));
    }

