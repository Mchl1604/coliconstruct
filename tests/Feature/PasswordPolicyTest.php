/**
 * One password policy, held to by every way a password comes into being.
 *
 * An uppercase letter, a lowercase letter, a number, a special character and
 * at least eight characters - whether the password is chosen at registration,
 * on the forced first-sign-in change, on the profile, through a forgotten
 * password reset, typed by an administrator, generated by the system, or
 * handed to the console repair. Passwords already stored are left alone.
 */
class PasswordPolicyTest extends TestCase
{
    use RefreshDatabase;

    private const STRONG = 'Str0ng#Passw0rd';

    /**
     * Each one misses at least one requirement, with the sentence that says
     * exactly what.
     *
     * @return array<string, array{0: string, 1: string}>
     */
    public static function weakPasswords(): array
    {
        return [
            'all lower case' => ['password', 'Password must contain at least one uppercase letter, one number and one special character.'],
            'no number or symbol' => ['Password', 'Password must contain at least one number and one special character.'],
            'no upper case or symbol' => ['password1', 'Password must contain at least one uppercase letter and one special character.'],
            'no symbol' => ['Password1', 'Password must contain at least one special character.'],
            'no number' => ['Password!', 'Password must contain at least one number.'],
            'no upper case or number' => ['password!', 'Password must contain at least one uppercase letter and one number.'],
            'no lower case' => ['PASSWORD1!', 'Password must contain at least one lowercase letter.'],
            'too short' => ['Pa1!', 'Password must be at least 8 characters long.'],
            'a space is not a symbol' => ['Pass word1', 'Password must contain at least one special character.'],
            'short and missing everything' => ['short', 'Password must be at least 8 characters long and contain at least one uppercase letter, one number and one special character.'],
        ];
    }

    /**
     * @return array<string, array{0: string}>
     */
    public static function strongPasswords(): array
    {
        return [
            'mixed with a bang' => ['Password1!'],
            'symbol in the middle' => ['Str0ng#Pass'],
            'dashes as symbols' => ['my-Secret-2026'],
            'exactly eight' => ['X9@yzabc'],
            'caret and ampersand' => ['a^B&c*D1'],
            'with spaces too' => ['Correct Horse 9!'],
            'other scripts alongside' => ['Ünïcode-Pass9'],
        ];
    }

    // ------------------------------------------------------------------
    // The policy itself
    // ------------------------------------------------------------------

    #[DataProvider('weakPasswords')]
    public function test_a_weak_password_is_refused_with_everything_it_lacks(string $password, string $message): void
    {
        $this->assertFalse(PasswordPolicy::isSatisfiedBy($password));
        $this->assertSame($message, PasswordPolicy::failureMessage($password));
    }

    #[DataProvider('strongPasswords')]
    public function test_a_password_with_every_kind_of_character_passes(string $password): void
    {
        $this->assertTrue(PasswordPolicy::isSatisfiedBy($password));
        $this->assertNull(PasswordPolicy::failureMessage($password));
    }

    public function test_the_checklist_is_drawn_from_the_same_patterns_the_server_tests(): void
    {
        $checklist = collect(PasswordPolicy::checklist())->keyBy('key');

        $this->assertSame(['length', 'uppercase', 'lowercase', 'number', 'symbol'], $checklist->keys()->all());
        $this->assertSame(PasswordPolicy::MIN_LENGTH, $checklist['length']['min_length']);

        foreach (PasswordPolicy::CHARACTER_REQUIREMENTS as $key => $requirement) {
            $this->assertSame($requirement['pattern'], $checklist[$key]['pattern']);
        }
    }

    // ------------------------------------------------------------------
    // Registration
    // ------------------------------------------------------------------

    #[DataProvider('weakPasswords')]
    public function test_registration_refuses_a_weak_password_even_when_confirmed(string $password, string $message): void
    {
        Mail::fake();

        $this->register($password)->assertSessionHasErrors(['password' => $message]);

        $this->assertDatabaseCount('tbl_pending_registrations', 0);
        Mail::assertNothingSent();
    }

    #[DataProvider('strongPasswords')]
    public function test_registration_accepts_a_strong_password(string $password): void
    {
        Mail::fake();

        $this->register($password)->assertRedirect(route('auth.verify'));

        $pending = PendingRegistration::where('email', 'jose@example.test')->firstOrFail();
        $this->assertTrue(Hash::check($password, $pending->password));
    }

    public function test_a_strong_password_still_has_to_match_its_confirmation(): void
    {
        $this->register(self::STRONG, 'Str0ng#Different')
            ->assertSessionHasErrors(['password' => 'The two passwords do not match.']);

        $this->assertDatabaseCount('tbl_pending_registrations', 0);
    }

    // ------------------------------------------------------------------
    // Forced first-sign-in change (temporary password replacement)
    // ------------------------------------------------------------------

    #[DataProvider('weakPasswords')]
    public function test_a_temporary_password_cannot_be_replaced_with_a_weak_one(string $password, string $message): void
    {
        $user = $this->account('admin', ['must_change_password' => true]);

        $this->actingAs($user)
            ->post(route('auth.password.update'), [
                'current_password' => 'Temp-pass-1',
                'password' => $password,
                'password_confirmation' => $password,
            ])
            ->assertSessionHasErrors(['password' => $message]);

        $user->refresh();
        $this->assertTrue(Hash::check('Temp-pass-1', $user->password));
        $this->assertTrue((bool) $user->must_change_password);
    }

    public function test_a_temporary_password_is_replaced_with_a_strong_one(): void
    {
        $user = $this->account('admin', ['must_change_password' => true]);

        $this->actingAs($user)
            ->post(route('auth.password.update'), [
                'current_password' => 'Temp-pass-1',
                'password' => self::STRONG,
                'password_confirmation' => self::STRONG,
            ])
            ->assertRedirect(route('super-admin.dashboard'));

        $user->refresh();
        $this->assertTrue(Hash::check(self::STRONG, $user->password));
        $this->assertFalse((bool) $user->must_change_password);
    }

