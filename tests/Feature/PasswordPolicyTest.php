    // ------------------------------------------------------------------
    // The checklist on every form
    // ------------------------------------------------------------------

    public function test_every_form_that_sets_a_password_shows_the_requirements(): void
    {
        $this->assertShowsRequirements($this->get(route('auth.register')), 'password');

        $temporary = $this->account('admin', ['must_change_password' => true]);
        $this->assertShowsRequirements($this->actingAs($temporary)->get(route('auth.password.change')), 'password');

        $member = $this->account('technician');
        $this->assertShowsRequirements($this->actingAs($member)->get(route('profile.edit')), 'newPassword');

        $this->actingAsSuperAdmin();
        $this->assertShowsRequirements($this->get(route('super-admin.configuration.index')), 'userTempPassword');

        auth()->logout();
        $client = $this->account('client');
        $this->verifyResetCodeFor($client);
        $this->assertShowsRequirements($this->get(route('auth.password.reset')), 'password');
    }

