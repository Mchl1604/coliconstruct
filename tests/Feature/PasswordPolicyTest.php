    public function test_every_generated_password_meets_the_policy(): void
    {
        $accounts = app(UserAccountService::class);

        foreach (range(1, 200) as $attempt) {
            $password = $accounts->generateTemporaryPassword();

            $this->assertTrue(
                PasswordPolicy::isSatisfiedBy($password),
