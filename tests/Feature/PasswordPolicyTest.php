        $this->assertTrue(Hash::check('Temp-pass-1', $user->refresh()->password));
    }

    public function test_the_profile_accepts_a_strong_new_password(): void
    {
        $user = $this->account('technician');

        $this->actingAs($user)
            ->put(route('profile.password'), [
                'current_password' => 'Temp-pass-1',
                'password' => self::STRONG,
