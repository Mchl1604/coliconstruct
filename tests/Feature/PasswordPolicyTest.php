            );
        }
    }

    /**
     * A Super Admin resetting an Admin, and the Admin then replacing what
     * they were issued: strong on the way out, strong on the way back in.
     */
    public function test_a_super_admin_reset_issues_a_strong_password_that_must_be_replaced_with_another(): void
    {
        $this->actingAsSuperAdmin();
        $admin = $this->account('admin');

        $issued = $this->putJson(route('super-admin.configuration.users.password.reset', $admin))
            ->assertOk()
            ->json('password');

        $admin->refresh();
        $this->assertTrue(PasswordPolicy::isSatisfiedBy($issued));
        $this->assertTrue(Hash::check($issued, $admin->password));
        $this->assertTrue((bool) $admin->must_change_password);

        auth()->logout();

        $this->post(route('auth.login.attempt'), ['email' => $admin->email, 'password' => $issued])
            ->assertRedirect(route('auth.password.change'));

        $this->post(route('auth.password.update'), [
            'current_password' => $issued,
            'password' => 'Password1',
            'password_confirmation' => 'Password1',
        ])->assertSessionHasErrors(['password' => 'Password must contain at least one special character.']);

        $this->assertTrue((bool) $admin->refresh()->must_change_password);

        $this->post(route('auth.password.update'), [
            'current_password' => $issued,
            'password' => self::STRONG,
            'password_confirmation' => self::STRONG,
        ])->assertRedirect(route('super-admin.dashboard'));

        $this->assertFalse((bool) $admin->refresh()->must_change_password);
    }

    public function test_an_admin_reset_of_an_employee_issues_a_strong_password(): void
    {
        $admin = $this->account('admin');
        $technician = $this->account('technician');

        $issued = $this->actingAs($admin)
            ->putJson(route('super-admin.configuration.users.password.reset', $technician))
            ->assertOk()
            ->json('password');

        $this->assertTrue(PasswordPolicy::isSatisfiedBy($issued));
        $this->assertTrue((bool) $technician->refresh()->must_change_password);
    }

