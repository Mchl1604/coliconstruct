    /**
     * @param  array<string, mixed>  $overrides
     */
    private function account(string $role, array $overrides = []): User
    {
        $sequence = User::count() + 1;

        return User::create(array_merge([
            'user_code' => ($role === 'client' ? 'CLI-' : 'EMP-').str_pad((string) (100 + $sequence), 4, '0', STR_PAD_LEFT),
            'name' => 'Test Person',
            'first_name' => 'Test',
            'last_name' => 'Person',
            'email' => 'person'.$sequence.'@example.test',
            'role' => $role,
            'status' => User::STATUS_ACTIVE,
            'email_verified_at' => now(),
            // Accounts the terms gate would otherwise stop at the door.
            'terms_accepted_version' => app(SystemContentService::class)->termsVersion(),
            'terms_accepted_at' => now(),
            'password' => 'Temp-pass-1',
        ], $overrides));
    }

    private function register(string $password, ?string $confirmation = null): TestResponse
    {
        return $this->post(route('auth.register.store'), [
            'full_name' => 'Jose Garcia',
            'email' => 'jose@example.test',
            'contact_number' => '09175551234',
            'birthdate' => '1990-05-04',
            'password' => $password,
            'password_confirmation' => $confirmation ?? $password,
            'terms' => '1',
        ]);
    }

    /**
     * Walk the forgotten-password flow up to the point where a new password
     * is asked for.
     */
    private function verifyResetCodeFor(User $user): void
    {
        Mail::fake();
        config(['mail.default' => 'smtp']);

        $this->post(route('auth.password.email'), ['email' => $user->email]);

        $code = null;
        Mail::assertSent(OtpCodeMail::class, function (OtpCodeMail $mail) use (&$code): bool {
            $code = $mail->code;

            return true;
        });

        $this->post(route('auth.password.verify.store'), ['code' => (string) $code])
            ->assertRedirect(route('auth.password.reset'));
    }

    private function assertShowsRequirements(TestResponse $response, string $inputId): void
    {
        $response->assertOk();
        $response->assertSee('data-password-requirements="'.$inputId.'"', false);
        $response->assertSee('/js/passwordField.js', false);

        foreach (PasswordPolicy::checklist() as $requirement) {
            $response->assertSee($requirement['label']);

            if ($requirement['pattern']) {
                $response->assertSee('data-pattern="'.e($requirement['pattern']).'"', false);
            }
        }
    }

    /**
     * Run with SUPER_ADMIN_PASSWORD set to this value, and put back whatever
     * was there after.
     */
    private function withSuperAdminPassword(string $value, callable $callback): void
    {
        $previous = [$_ENV['SUPER_ADMIN_PASSWORD'] ?? null, $_SERVER['SUPER_ADMIN_PASSWORD'] ?? null, getenv('SUPER_ADMIN_PASSWORD')];

        $_ENV['SUPER_ADMIN_PASSWORD'] = $_SERVER['SUPER_ADMIN_PASSWORD'] = $value;
        putenv('SUPER_ADMIN_PASSWORD='.$value);

        try {
            $callback();
        } finally {
            [$env, $server, $put] = $previous;

            if ($env === null) {
                unset($_ENV['SUPER_ADMIN_PASSWORD']);
            } else {
                $_ENV['SUPER_ADMIN_PASSWORD'] = $env;
            }

            if ($server === null) {
                unset($_SERVER['SUPER_ADMIN_PASSWORD']);
            } else {
                $_SERVER['SUPER_ADMIN_PASSWORD'] = $server;
            }

            putenv($put === false ? 'SUPER_ADMIN_PASSWORD' : 'SUPER_ADMIN_PASSWORD='.$put);
        }
    }
